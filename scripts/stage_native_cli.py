"""Stage the repository's Go CLI sources into a prepared desktop checkout."""
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'research/cli/native'


def stage_native_cli(upstream):
    target = upstream / 'app/native/paper-reed-cli'
    if target.is_symlink() or target.parent.is_symlink():
        raise RuntimeError(f'Cannot stage native CLI sources through a symlink: {target}')
    target.mkdir(parents=True, exist_ok=True)
    sources = [
        path for path in sorted(SOURCE.iterdir())
        if path.suffix in ('.go', '.mod', '.json') and not path.name.endswith('_test.go')
    ]
    filenames = {source.name for source in sources}
    # This directory is generated by Paper Reed. Remove obsolete staged inputs.
    for old in target.iterdir():
        if old.suffix in ('.go', '.mod', '.json') and old.name not in filenames and not old.is_dir():
            old.unlink()
    for source in sources:
        staged = target / source.name
        if staged.is_symlink():
            raise RuntimeError(f'Cannot overwrite a symlink while staging the native CLI: {staged}')
        shutil.copy2(source, staged)
    return [str((target / name).relative_to(upstream)) for name in filenames]


def require_go():
    required = re.search(r'^go (\d+)\.(\d+)', (SOURCE / 'go.mod').read_text(), re.M)
    minimum = tuple(map(int, required.groups()))
    go = shutil.which('go')
    if go:
        try:
            result = subprocess.check_output(
                [go, 'env', 'GOVERSION'], text=True, env={**os.environ, 'GOTOOLCHAIN': 'local'},
                stderr=subprocess.DEVNULL,
            )
        except subprocess.CalledProcessError:
            result = ''
        installed = re.search(r'\bgo(\d+)\.(\d+)', result)
        if installed and tuple(map(int, installed.groups())) >= minimum:
            return
    raise RuntimeError(f'Building the Paper Reed CLI requires Go {minimum[0]}.{minimum[1]} or newer on PATH.')
